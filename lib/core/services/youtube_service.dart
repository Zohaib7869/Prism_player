class YoutubeDownloadOption {
  final String label;
  final bool audioOnly;
  final String? videoUrl;
  final String audioUrl;

  final int videoBytes;
  final int audioBytes;

  /// Request headers the URLs above were signed/authorized for. Null means
  /// "use the legacy per-client headers from [YoutubeService.streamHeadersFor]"
  /// — set for options resolved via the native yt-dlp path
  /// ([YoutubeNativeDownloadResolver]), where yt-dlp itself decides which
  /// headers the URL needs and they must be sent back exactly as given.
  final Map<String, String>? headers;

  /// yt-dlp's own `-f` selector string that produced this option, e.g.
  /// `"bestvideo[height<=720]+bestaudio/best[height<=720]"`. Null for
  /// options from the legacy youtube_explode_dart path. Stored so a later
  /// retry can re-resolve fresh URLs the same way instead of falling back
  /// to the old manifest-based refresh.
  final String? nativeFormatSelector;

  const YoutubeDownloadOption({
    required this.label,
    required this.audioOnly,
    required this.audioUrl,
    this.videoUrl,
    this.videoBytes = 0,
    this.audioBytes = 0,
    this.headers,
    this.nativeFormatSelector,
  });

  int get totalBytes => videoBytes + audioBytes;
  String get extension => audioOnly ? 'm4a' : 'mp4';

  String get readableSize {
    final bytes = totalBytes;
    if (bytes <= 0) return '';
    if (bytes >= 1024 * 1024 * 1024) {
      return '${(bytes / (1024 * 1024 * 1024)).toStringAsFixed(2)} GB';
    }
    return '${(bytes / (1024 * 1024)).toStringAsFixed(1)} MB';
  }
}

const String kYoutubeUserAgent =
    'com.google.android.apps.youtube.vr.oculus/1.56.21 (Linux; U; Android 12; en_US; Quest 3 Build/SQ3A.220605.009.A1) gzip';

const Map<String, String> kYoutubeStreamHttpHeaders = {
  'user-agent': kYoutubeUserAgent,
};

class _YtClientProfile {
  final String name;
  final yt.YoutubeApiClient client;
  final String userAgent;

  const _YtClientProfile(this.name, this.client, this.userAgent);

  Map<String, String> get headers => {'user-agent': userAgent};
}

/// A successful resolve, returned by [YoutubeService._tryClient] *without*
/// touching any shared per-video state. Profiles are now tried concurrently,
/// so the loser of a race must not be able to overwrite `_profileFor` (and
/// therefore the User-Agent mpv is handed) behind the winner's back — only
/// the caller commits, via `_commit`.
class _Resolved {
  final YoutubeStream stream;
  final _YtClientProfile profile;
  final yt.StreamManifest manifest;
  final bool adaptive;

  /// Best muxed (progressive) URL from the *same* manifest, worked out at
  /// resolve time and kept on hand. When mpv rejects the adaptive pair, the
  /// fallback is then already in memory — previously that path went and
  /// fetched a whole second manifest plus a fresh round of probes, which is
  /// the bulk of the delay you see between tapping a video and it playing.
  final String? preparedFallbackUrl;

  const _Resolved(
    this.stream,
    this.profile,
    this.manifest,
    this.adaptive, {
    this.preparedFallbackUrl,
  });
}

/// googlevideo URLs carry an `expire` query param roughly 6h out, but they
/// start 403-ing well before that once the session that minted them goes
/// stale. Two hours is comfortably inside that window.
const Duration _kStreamCacheTtl = Duration(hours: 2);

class _CachedStream {
  final Future<YoutubeStream> future;
  final DateTime createdAt;

  _CachedStream(this.future) : createdAt = DateTime.now();

  bool get isStale => DateTime.now().difference(createdAt) > _kStreamCacheTtl;
}

